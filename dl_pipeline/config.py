def ensure_output_dir() -> str:
    """
    Create the output directory (and any missing parent directories) if absent.

    This is called automatically when ``config`` is imported, so downstream
    modules can write artefacts without performing their own ``os.makedirs``.

    Returns
    -------
    str
        Absolute path to ``OUTPUT_DIR``.
    """
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    return OUTPUT_DIR


def get_data_yaml_path() -> str:
    """
    Build the expected path to the ``data.yaml`` configuration file.

    ``data.yaml`` is generated by ``step1_prepare_data.py`` and consumed by
    YOLOv8's training, validation, and inference routines.

    Returns
    -------
    str
        Absolute path to ``<DATASET_PATH>/data.yaml``.
    """
    return os.path.join(DATASET_PATH, "data.yaml")


def print_config() -> None:
    """
    Print a formatted summary of the current pipeline configuration to stdout.

    Useful for verifying settings before a long training run.
    Covers dataset path, model variant, class count, key hyperparameters,
    compute device, and output directory.
    """
    print("\n" + "=" * 60)
    print("DL PIPELINE CONFIGURATION")
    print("=" * 60)
    print(f"  Dataset: {DATASET_PATH}")
    print(f"  Model: YOLOv8{MODEL_SIZE}-seg")
    print(f"  Classes: {NUM_CLASSES}")
    print(f"  Epochs: {EPOCHS}")
    print(f"  Batch Size: {BATCH_SIZE}")
    print(f"  Image Size: {IMAGE_SIZE}x{IMAGE_SIZE}")
    print(f"  Device: {DEVICE}")
    print(f"  Output: {OUTPUT_DIR}")
    print("=" * 60 + "\n")


# Ensure the output directory is ready as soon as this module is imported.
ensure_output_dir()
