# ============================================================================
# GPU SETTINGS
# ============================================================================

def get_device() -> str:
    """
    Detect the best available compute device and print a status message.

    Checks for a CUDA-capable GPU via ``torch.cuda.is_available()``.
    If one is found, prints its name and total VRAM; otherwise falls back
    to the CPU with a performance warning.

    Returns
    -------
    str
        ``'cuda'`` when a GPU is available, ``'cpu'`` otherwise.
    """
    if torch.cuda.is_available():
        device = 'cuda'
        gpu_name = torch.cuda.get_device_name(0)
        gpu_mem  = torch.cuda.get_device_properties(0).total_memory / 1e9
        print(f"✅ GPU detected: {gpu_name} ({gpu_mem:.1f} GB)")
    else:
        device = 'cpu'
        print("⚠️ No GPU detected, using CPU (training will be slow)")
    return device


# Module-level device string; imported directly when a function call is not needed.
DEVICE: str = 'cuda' if torch.cuda.is_available() else 'cpu'


